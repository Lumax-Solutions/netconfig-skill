#!/usr/bin/env python3
"""Build a single-file version of the skill for tools that don't support Agent Skills.

Produces dist/AGENTS.md: the core SKILL.md (without frontmatter) followed by every
reference file. Use it as an AGENTS.md, a custom-instructions file, or a system prompt.

Options:
  --only fortigate,cisco-ios   include only these reference files (smaller prompt)
  --out PATH                   output path (default: dist/AGENTS.md)
"""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILL = ROOT / "network-device-config"

ap = argparse.ArgumentParser()
ap.add_argument("--only", default="", help="comma-separated reference names (without .md)")
ap.add_argument("--out", default=str(ROOT / "dist" / "AGENTS.md"))
args = ap.parse_args()

core = (SKILL / "SKILL.md").read_text(encoding="utf-8")
meta = re.match(r"^---\n(.*?)\n---\n", core, re.S)
version = re.search(r'version:\s*"?([^"\n]+)', meta.group(1)).group(1) if meta else "?"
core = core[meta.end():] if meta else core

# In the single-file build every reference is inline, so rewrite the routing instruction.
core = core.replace(
    "**Before writing any config, read the reference file(s) for the platform(s) involved**",
    "**Before writing any config, consult the platform section(s) below for the platform(s) involved**",
)

wanted = {w.strip() for w in args.only.split(",") if w.strip()}
refs = sorted((SKILL / "references").glob("*.md"))
if wanted:
    refs = [r for r in refs if r.stem in wanted]

out = [
    f"<!-- Generated by scripts/build_agents_md.py from network-device-config v{version}. Do not edit by hand. -->\n",
    core.strip(),
    "\n\n---\n\n# Platform references\n",
]
for r in refs:
    text = r.read_text(encoding="utf-8")
    text = re.sub(r"^Part of the `network-device-config` skill\..*\n", "", text, flags=re.M)
    # demote headings one level so they sit under "Platform references"
    text = re.sub(r"(?m)^(#{1,5}) ", lambda m: "#" + m.group(1) + " ", text)
    out.append(f"\n<!-- references/{r.name} -->\n" + text.strip() + "\n")

dest = pathlib.Path(args.out)
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out), encoding="utf-8")
print(f"Wrote {dest} ({dest.stat().st_size // 1024} KB, {len(refs)} reference sections)")
